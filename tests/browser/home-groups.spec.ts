import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, sep } from 'node:path';
import { expect, test } from '@playwright/test';
import { App } from '../../apps/daemon/src/app.ts';
import { startServer, type RunningServer } from '../../apps/daemon/src/server.ts';

let dir: string, app: App, server: RunningServer;
test.beforeAll(async () => { dir = mkdtempSync(join(tmpdir(), 'drishya-home-')); app = new App(dir); server = await startServer({ app, port: 0, token: 'synthetic-home' }); });
test.afterAll(async () => { await server.close(); await app.close(); if (!resolve(dir).startsWith(resolve(tmpdir()) + sep)) throw new Error('unsafe temporary path'); rmSync(dir, { recursive: true, force: true }); });

test('Home groups complete matching metadata and bounds rows, with keyboard/narrow access', async ({ page }) => {
  const today = new Date().toISOString();
  const yesterday = new Date(); yesterday.setDate(yesterday.getDate() - 1);
  const rows = Array.from({ length: 105 }, (_, n) => ({ id: `r-${n}`, title: `Synthetic session ${n}`, harness: n % 2 ? 'codex' : 'claude-code', workspaceRoot: n === 104 ? undefined : n === 103 ? '/two/shop' : '/one/shop', createdAt: today, updatedAt: today, lastSourceTime: n === 104 ? undefined : n === 1 ? yesterday.toISOString() : today, observationCount: 2, live: n === 0, pinned: false }));
  await page.route('**/v1/recordings', route => route.fulfill({ json: { recordings: rows } }));
  await page.route('**/v1/sources', route => route.fulfill({ json: { sources: [{ adapterId: 'codex', harness: 'codex', path: '/synthetic/session', bytes: 100, modifiedAt: today, cwd: '/two/shop', title: 'Native source', importedRecordingId: 'r-103', companions: [] }], errors: [] } }));
  await page.goto(server.launchUrl);
  const recordings = page.locator('.home-grid > section').first();
  await expect(recordings).toContainText('105 matching');
  await expect(recordings.locator('.workspace-group-heading')).toHaveCount(3);
  await expect(recordings).toContainText('/one/shop');
  await expect(recordings).toContainText('/two/shop');
  await expect(recordings).toContainText('Time unavailable');
  expect(await recordings.locator('.row').count()).toBe(22);
  const first = recordings.locator('.workspace-group-heading').first();
  await first.focus(); await page.keyboard.press('Enter');
  await expect(first).toHaveAttribute('aria-expanded', 'false');
  await expect(recordings.locator('.row')).toHaveCount(2);
  await page.keyboard.press('Enter');
  await expect(first).toHaveAttribute('aria-expanded', 'true');
  await recordings.getByRole('button', { name: /Show more sessions/ }).click();
  await expect(recordings.locator('.row')).toHaveCount(42);
  await recordings.getByRole('checkbox', { name: 'Select Synthetic session 0 to open together' }).check();
  await page.getByRole('textbox', { name: 'Find a session' }).fill('Synthetic session 1');
  await expect(recordings).toContainText('1 selected');
  await expect(recordings).toContainText('Yesterday');
  await page.getByRole('textbox', { name: 'Find a session' }).fill('Native source');
  await expect(page.locator('.home-grid > section').last()).toContainText('Imported');
  await page.getByRole('textbox', { name: 'Find a session' }).fill('no-match');
  await expect(recordings).toContainText('No imported recordings match');
  await page.getByRole('textbox', { name: 'Find a session' }).fill('');
  await page.getByRole('combobox', { name: 'Harness', exact: true }).selectOption('codex');
  await expect(recordings).toContainText('52 matching');
  await page.getByRole('combobox', { name: 'Harness', exact: true }).selectOption('all');
  await page.getByRole('combobox', { name: 'Session age' }).selectOption('1');
  await expect(recordings).not.toContainText('Time unavailable');
  await page.getByRole('combobox', { name: 'Session age' }).selectOption('0');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.getByRole('textbox', { name: 'Find a session' })).toBeVisible();
});
