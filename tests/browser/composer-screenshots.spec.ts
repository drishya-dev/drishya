import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,rmSync} from 'node:fs';
import {join,resolve,sep} from 'node:path';
import {tmpdir} from 'node:os';
import {spawn} from 'node:child_process';
import {test,expect} from '@playwright/test';
import {App} from '../../apps/daemon/src/app.ts';
import {startServer,type RunningServer} from '../../apps/daemon/src/server.ts';
import {HarnessController} from '../../apps/daemon/src/controller.ts';

let dir:string,app:App,server:RunningServer,id:string;
const png=readFileSync(resolve('apps/ui/public/brand/drishya-192.png'));
test.beforeAll(async()=>{
  dir=mkdtempSync(join(tmpdir(),'drishya-screenshot-composer-'));
  const root=join(dir,'repository');mkdirSync(root);
  const journal=join(dir,'session.jsonl');
  writeFileSync(journal,JSON.stringify({sessionId:'5c154560-6498-4449-85ef-335191e2b160',cwd:root,timestamp:'2026-11-06T12:00:00Z',type:'user',uuid:'initial',message:{role:'user',content:'Screenshot preparation regression'}})+'\n');
  const transport=join(dir,'transport.mjs');
  writeFileSync(transport,`import{createInterface}from'node:readline';import{writeFileSync}from'node:fs';const send=v=>process.stdout.write(JSON.stringify(v)+'\\n');createInterface({input:process.stdin}).on('line',line=>{const v=JSON.parse(line);if(v.type==='control_request')send({type:'control_response',response:{subtype:'success',request_id:v.request_id,response:{}}});if(v.type==='user'){writeFileSync(${JSON.stringify(join(dir,'received.json'))},JSON.stringify(v));send({type:'result',is_error:false});}});`);
  app=new App(join(dir,'store'));id=(await app.ingest.importSource('claude-code',journal)).recordingId;
  server=await startServer({app,port:0,controllerFactory:(a,w)=>new HarnessController(a,w,{resolveExecutable:()=>process.execPath,launch:((_bin:string,_args:string[],opts:any)=>spawn(process.execPath,[transport],opts)) as typeof spawn})});
});
test.afterAll(async()=>{await server?.close();await app?.close();if(dir){if(!resolve(dir).startsWith(resolve(tmpdir())+sep))throw Error('unsafe cleanup');rmSync(dir,{recursive:true,force:true});}});

for(const width of [600,1440]) test(`screenshot paste and pick, honest failures, ${width}px`,async({page,context})=>{
  await context.grantPermissions(['clipboard-read','clipboard-write']);
  await page.setViewportSize({width,height:900});
  await page.route('**/v1/working-locations',route=>route.request().method()==='GET'?route.fulfill({json:{version:1,sessions:[]}}):route.continue());
  await page.goto(server.launchUrl);await expect(page.locator('.home')).toBeVisible();
  await page.goto(`${server.url}/?experience=modern&motion=0#/r/${id}`);
  const composer=page.getByRole('region',{name:'Harness prompt'});
  await expect(composer.locator('.composer-minimize')).toBeVisible();
  if(await composer.locator('.composer-minimize').getAttribute('aria-expanded')==='false')await composer.locator('.composer-minimize').click();
  await composer.locator('.native-options > summary').click();
  const enable=composer.getByRole('button',{name:'Enable this workspace',exact:true});
  if(await enable.isVisible())await enable.click();
  await composer.locator('.native-options > summary').click();
  const input=composer.locator('input[aria-label="Choose prompt files"]');
  await input.setInputFiles({name:'unsupported.heic',mimeType:'image/heic',buffer:Buffer.from('not a supported image')});
  await expect(composer.getByRole('alert')).toContainText('not supported');
  await input.setInputFiles({name:'oversized.png',mimeType:'image/png',buffer:Buffer.concat([png,Buffer.alloc(4*1024*1024)])});
  await expect(composer.getByRole('alert')).toContainText('4 MiB');
  await expect(composer.locator('.attachment-chip')).toHaveCount(0);
  const textbox=composer.getByRole('textbox');await textbox.fill('Keep this draft');
  await page.evaluate(async data=>navigator.clipboard.write([new ClipboardItem({'image/png':new Blob([Uint8Array.from(atob(data),c=>c.charCodeAt(0))],{type:'image/png'})})]),png.toString('base64'));
  await textbox.focus();await page.keyboard.press('Control+v');
  await expect(composer.locator('.attachment-chip')).toHaveCount(1);await expect(textbox).toHaveValue('Keep this draft');
  const chooser=page.waitForEvent('filechooser');await composer.getByRole('button',{name:'Attach text or image files',exact:true}).click();
  await(await chooser).setFiles({name:'picked-screenshot.png',mimeType:'application/octet-stream',buffer:png});
  await expect(composer.locator('.attachment-chip img')).toHaveCount(2);
  await expect.poll(()=>composer.locator('.attachment-chip img').evaluateAll(nodes=>nodes.every(node=>(node as HTMLImageElement).complete&&(node as HTMLImageElement).naturalWidth>0))).toBe(true);
  await composer.getByRole('button',{name:'Preview attachment picked-screenshot.png',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Attachment: picked-screenshot.png'}).getByRole('img')).toBeVisible();
  await page.getByRole('dialog',{name:'Attachment: picked-screenshot.png'}).getByRole('button',{name:'Close Attachment: picked-screenshot.png',exact:true}).click();
  await composer.getByRole('button',{name:'Send prompt',exact:true}).click();
  await composer.getByRole('checkbox',{name:'This session is idle in other clients'}).check();
  await composer.getByRole('button',{name:'Confirm and send',exact:true}).click();
  await expect.poll(()=>{try{return JSON.parse(readFileSync(join(dir,'received.json'),'utf8')).message.content.filter((x:any)=>x.type==='image').length;}catch{return 0;}}).toBe(2);
  const images=JSON.parse(readFileSync(join(dir,'received.json'),'utf8')).message.content.filter((x:any)=>x.type==='image');
  expect(images.every((image:any)=>image.source.media_type==='image/png'&&Buffer.from(image.source.data,'base64').subarray(0,8).equals(png.subarray(0,8)))).toBe(true);
  expect(images[1].source.data).toBe(png.toString('base64'));
  await expect(composer.locator('.attachment-chip')).toHaveCount(0);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
