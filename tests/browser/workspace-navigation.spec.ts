import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, sep } from 'node:path';
import { expect, test } from './legacy-test.ts';
import { expandCard } from './history-gestures.ts';
import { App } from '../../apps/daemon/src/app.ts';
import { startServer, type RunningServer } from '../../apps/daemon/src/server.ts';
let dir: string, app: App, server: RunningServer;
test.beforeAll(async () => { dir = mkdtempSync(join(tmpdir(), 'drishya-navigation-')); app = new App(dir); server = await startServer({ app, port: 0, token: 'synthetic-nav' }); });
test.afterAll(async () => { await server.close(); await app.close(); if (!resolve(dir).startsWith(resolve(tmpdir()) + sep)) throw new Error('unsafe temporary path'); rmSync(dir, { recursive: true, force: true }); });
test('keyboard navigation opens exact captured file work and keeps underlying reading on Escape', async ({ page }) => {
  await page.goto(new URL('/?demo', server.launchUrl).href);
  await expect(page.locator('.viewer')).toBeVisible();
  await page.keyboard.press('Control+k');
  const navigation = page.getByRole('dialog', { name: 'Navigate workspace' });
  await expect(navigation).toBeVisible();
  const search = navigation.getByRole('combobox', { name: 'Find a command, file or session' });
  await search.fill('guard.ts');
  await expect(navigation.getByRole('option')).toHaveCount(1);
  await search.press('Enter');
  const reading = page.getByRole('dialog', { name: 'Work on src/checkout/guard.ts' });
  await expect(reading).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(reading).toHaveCount(0);
  const op = page.locator('article.op-edit').first();
  await expandCard(op);
  await op.getByRole('button', { name: 'Open provenance and file states' }).press('Enter');
  const inspector = page.getByRole('complementary', { name: 'Operation detail' });
  await expect(inspector).toBeVisible();
  await page.keyboard.press('Control+k');
  await expect(navigation).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(navigation).toHaveCount(0); await expect(inspector).toBeVisible();
  await page.keyboard.press('Control+k');
  await search.fill('workspace settings'); await search.press('Enter');
  await expect(page.getByRole('dialog', { name: 'Workspace settings' })).toBeVisible();
  await page.keyboard.press('Escape'); await expect(inspector).toBeVisible();
});
