    rows.push({ ...base, uuid: `distant-call-${n}`, type: 'assistant', message: { id: `distant-msg-${n}`, role: 'assistant', content: [{ type: 'tool_use', id: `distant-${n}`, name: 'Read', input: { file_path: '/home/dev/shop/src/distant.ts', offset: 1, limit: 1 } }] } });
