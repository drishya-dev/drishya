import type { Hunk, Operation } from '@drishya/contracts';

/** Prose reads better wrapped; code reads better on its own lines. */
export const isProse = (path: string) => /\.(md|mdx|markdown|txt|rst|adoc|tex)$/i.test(path);

/** Added and removed lines of a captured patch, counted from its unified lines. */
export function diffStat(hunks: Hunk[]): { added: number; removed: number } {
  let added = 0, removed = 0;
  for (const hunk of hunks) for (const line of hunk.lines) { if (line[0] === '+') added++; else if (line[0] === '-') removed++; }
  return { added, removed };
}

// Gutters, sign column and padding around the code, then one mono character at 12px.
const CHROME = 130, CHARACTER = 7.3;
/** Reading width for a diff card, from its longest changed or context line, bounded to the passage. */
export function diffCardWidth(hunks: Hunk[], max = 860, min = 440): number {
  let longest = 0;
  for (const hunk of hunks) for (const line of hunk.lines.slice(0, 400)) longest = Math.max(longest, Math.min(140, line.length - 1));
  return Math.max(min, Math.min(max, Math.round(CHROME + longest * CHARACTER)));
}

/** What a card's evidence is and where it stops. One popover per card carries this; the card stays quiet. */
export function evidenceNotes(op: Operation): string[] {
  const d = op.detail;
  const notes: string[] = [];
  switch (d.kind) {
    case 'edit':
      notes.push(d.hunks.length ? 'The changes shown are the patch, not the current file.' : 'No patch was recorded for this change.');
      notes.push(d.reconstruction === 'complete' ? 'The after-state was reconstructed from the base.' : 'The after-state is not verified.');
      break;
    case 'read':
      notes.push('Historical source: the excerpt the harness recorded for this read. The file on disk may differ now.');
      break;
    case 'shell':
    case 'test':
      notes.push('The command and its output are recorded. Long output is a preview; Expand shows more.');
      break;
    case 'search':
      notes.push('These are the matches the harness recorded for this search.');
      break;
    default:
      notes.push('The arguments are the request. Long values are previews; Expand shows the full text.');
  }
  if (op.status === 'unknown') notes.push('The harness did not expose the outcome of this operation.');
  const how = op.classification;
  notes.push(how.kind === 'derived' ? `The type "${op.kind}" is derived by rule ${how.rule} from the command text. The content itself is recorded.`
    : how.kind === 'generated' ? `The type "${op.kind}" was generated by ${how.generator}, not recorded by the harness.`
    : `The type comes from the harness tool "${op.tool}".`);
  return notes;
}
