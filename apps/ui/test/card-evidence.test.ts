import type {Hunk,Operation} from '@drishya/contracts';
import {expect,it} from 'vitest';
import {diffCardWidth,diffStat,evidenceNotes} from '../src/lib/card-evidence.ts';

const hunk=(lines:string[]):Hunk=>({oldStart:1,oldLines:1,newStart:1,newLines:1,lines});
const op=(detail:Operation['detail'],extra:Partial<Operation>={}):Operation=>({id:'op',agentId:'agent:main',kind:'edit',tool:'apply_patch',title:'Edit a.ts',titleProvenance:{kind:'derived',rule:'t',observationIds:[]},origin:{type:'native',tool:'apply_patch'},status:'ok',startSequence:1,paths:[],detail,artifactIds:[],observationIds:[],classification:{kind:'captured',observationIds:[]},...extra});

it('counts only added and removed lines of a captured patch',()=>{
  expect(diffStat([hunk([' ctx','+a','+b','-c',' ctx']),hunk(['-d'])])).toEqual({added:2,removed:2});
  expect(diffStat([])).toEqual({added:0,removed:0});
});

it('sizes a diff card from its longest line, within the passage bounds',()=>{
  expect(diffCardWidth([hunk(['+short'])])).toBe(440);
  const mid=diffCardWidth([hunk(['+'+'x'.repeat(60)])]);expect(mid).toBeGreaterThan(440);expect(mid).toBeLessThan(860);
  expect(diffCardWidth([hunk(['+'+'x'.repeat(300)])])).toBe(860);
  expect(diffCardWidth([hunk(['+'+'x'.repeat(300)])],700)).toBe(700);
});

it('explains evidence per kind without presenting derived content as captured',()=>{
  const edit=evidenceNotes(op({kind:'edit',path:'a.ts',hunks:[hunk(['+a'])],created:false,reconstruction:'complete'}));
  expect(edit.join(' ')).toContain('captured patch, not the current file');expect(edit.join(' ')).toContain('reconstructed from the captured base');
  const unverified=evidenceNotes(op({kind:'edit',path:'a.ts',hunks:[],created:false,reconstruction:'unavailable'},{status:'unknown'}));
  expect(unverified.join(' ')).toContain('No patch was captured');expect(unverified.join(' ')).toContain('not verified');expect(unverified.join(' ')).toContain('did not expose the outcome');
  const derived=evidenceNotes(op({kind:'edit',path:'a.ts',hunks:[],created:false,reconstruction:'complete'},{classification:{kind:'derived',rule:'exec-edit',observationIds:[]}}));
  expect(derived.at(-1)).toContain('derived by rule exec-edit');expect(derived.at(-1)).toContain('content itself is captured');
  const generated=evidenceNotes(op({kind:'edit',path:'a.ts',hunks:[],created:false,reconstruction:'complete'},{classification:{kind:'generated',generator:'nemotron',observationIds:[]}}));
  expect(generated.at(-1)).toContain('generated by nemotron');
  expect(evidenceNotes(op({kind:'read',path:'a.ts',startLine:1,lineCount:3} as Operation['detail'],{kind:'read'})).join(' ')).toContain('Historical source');
});

it('keeps prose files wrapped and code files unwrapped',async()=>{
  const {isProse}=await import('../src/lib/card-evidence.ts');
  for(const path of ['docs/a.md','notes.TXT','x/readme.mdx','spec.rst'])expect(isProse(path)).toBe(true);
  for(const path of ['src/a.ts','a.md.bak','Makefile','styles.css'])expect(isProse(path)).toBe(false);
});
