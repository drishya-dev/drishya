// Keeps the priority tables in docs/TASKS.md honest: each row's Done mark (☑ / ☐) is set from the item's
// own checkbox in the detail section, and each priority heading carries a count.
//   node scripts/sync-tasks.ts          rewrite docs/TASKS.md in place
//   node scripts/sync-tasks.ts --check  exit 1 if the tables are out of date (changes nothing)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const path = fileURLToPath(new URL('../docs/TASKS.md', import.meta.url));
const raw = readFileSync(path, 'utf8');
const crlf = raw.includes('\r\n');
const text = raw.replaceAll('\r\n', '\n');

const ID = '[A-Z]+-\\d+[a-z]?';
// The detail section is the only place an item has a checkbox: "- [x] **READ-1 · …".
const done = new Set([...text.matchAll(new RegExp(`^- \\[x\\] \\*\\*(${ID}) `, 'gm'))].map((m) => m[1]!));
const known = new Set([...text.matchAll(new RegExp(`^- \\[[ x]\\] \\*\\*(${ID}) `, 'gm'))].map((m) => m[1]!));

const lines = text.split('\n');
const start = lines.findIndex((l) => l.startsWith('## 1. Priority order'));
const end = lines.findIndex((l, i) => i > start && /^## /.test(l));
const counts = new Map<string, { done: number; total: number }>();
let priority = '';
let inTable = false;
let columns = 5;
for (let i = start; i < end; i++) {
  const line = lines[i]!;
  const heading = /^### (P\d)\b/.exec(line);
  if (heading) { priority = heading[1]!; counts.set(priority, { done: 0, total: 0 }); inTable = false; continue; }
  if (!priority || !line.startsWith('|')) { inTable = false; continue; }
  const cells = line.split('|').slice(1, -1).map((c) => c.trim());
  const body = /^[☑☐]$/.test(cells[0] ?? '') ? cells.slice(1) : cells;   // drop an existing Done cell
  if (inTable && body[0] === 'Done') body.shift();                        // a stray header word pasted into a data row (13 Nov)
  const idAt = body.findIndex((c) => new RegExp(`^${ID}$`).test(c));
  if (!inTable) {                                                          // header row, then the separator
    if (/^-+$/.test(cells[0] ?? '')) { lines[i] = `|${Array(columns).fill('---').join('|')}|`; inTable = true; continue; }
    const named = body.filter((cell) => cell !== 'Done');
    columns = named.length + 1;
    lines[i] = `| Done | ${named.join(' | ')} |`;
    continue;
  }
  if (idAt < 0) continue;
  const id = body[idAt]!;
  const mark = done.has(id) ? '☑' : '☐';
  const tally = counts.get(priority)!;
  tally.total++; if (done.has(id)) tally.done++;
  lines[i] = `| ${mark} | ${body.join(' | ')} |`;
  if (!known.has(id)) console.log(`note: ${id} is in the priority list but has no checkbox entry in the detail section`);
}

// "**4 of 18 done**" under each priority heading, and an overall figure under the section title.
const summary = (n: { done: number; total: number }) => `**${n.done} of ${n.total} done**`;
const upsert = (headingIndex: number, value: string) => {
  let at = headingIndex + 1;
  while (lines[at] === '') at++;
  if (/^\*\*(Overall: )?\d+ of \d+ done/.test(lines[at] ?? '')) lines[at] = value;
  else lines.splice(headingIndex + 1, 0, '', value);
};
for (const [p, n] of [...counts].reverse()) {
  const at = lines.findIndex((l, i) => i > start && l.startsWith(`### ${p}`));
  upsert(at, summary(n));
}
const total = [...counts.values()].reduce((a, n) => ({ done: a.done + n.done, total: a.total + n.total }), { done: 0, total: 0 });
upsert(start, `**Overall: ${total.done} of ${total.total} done.** Marks are generated by \`node scripts/sync-tasks.ts\` from each item's checkbox below; tick the item, then run it.`);

const out = lines.join('\n');
if (process.argv.includes('--check')) {
  if (out !== text) { console.error('docs/TASKS.md priority tables are out of date: run node scripts/sync-tasks.ts'); process.exit(1); }
  console.log('priority tables are up to date');
} else {
  writeFileSync(path, crlf ? out.replaceAll('\n', '\r\n') : out);
  for (const [p, n] of counts) console.log(`${p}: ${n.done}/${n.total} done`);
  console.log(`overall: ${total.done}/${total.total}`);
}
